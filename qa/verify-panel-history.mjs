import fs from 'node:fs';
import assert from 'node:assert/strict';
import {build} from 'esbuild';
const out='qa/historial-panel-2026-10-15';fs.mkdirSync(out,{recursive:true});
await build({stdin:{contents:"export * from './src/data/panelHistory';export * from './src/data/session';export * from './src/data/changes';export * from './src/data/practice';export * from './src/data/wiring';",resolveDir:process.cwd()},bundle:true,platform:'node',format:'cjs',outfile:out+'/model.cjs',logLevel:'silent'});
const m=await import('./historial-panel-2026-10-15/model.cjs?'+Date.now()),checks=[];
const empty=m.emptyPractice(),wire=m.createCable('CONTACTOR_TERMICO:95','CONTACTOR_TERMICO:96',[]);
const add={...empty,wires:[wire]},color={...add,wires:[{...wire,color:'#c53943'}]},route={...color,wires:[{...color.wires[0],route:{sag:250}}]},removed={...route,wires:[]};
let h=m.newPanelHistory(empty);
for(const p of [add,color,route,removed])h=m.appendPanelHistory(h,{practice:p},m.practiceChange((h.steps.at(-1)?.frame||h.initial).practice,p).label,[],'edit');
assert.equal(h.steps[0].changes.added[0].id,wire.id);
assert.deepEqual(h.steps[1].changes.modified[0].fields,['color']);
assert.equal(h.steps[1].changes.modified[0].before.color,wire.color);
assert.equal(h.steps[1].changes.modified[0].after.color,'#c53943');
assert.deepEqual(h.steps[2].changes.modified[0].fields,['route']);
assert.equal(h.steps[3].changes.removed[0].route.sag,250);
assert.match(h.steps[3].label,/Retirar/);
assert.equal(m.appendPanelHistory(h,{practice:removed},'sin cambios'),h);
checks.push('Altas, bajas, color y recorrido con valores anteriores/posteriores; no se registran cambios inexistentes.');
h=m.appendPanelHistory(h,{practice:route},'Deshacer · recuperar',[],'undo');
h=m.appendPanelHistory(h,{practice:removed},'Rehacer · retirar',[],'redo');
assert.equal(h.steps.at(-2).operation,'undo');assert.equal(h.steps.at(-2).changes.added[0].id,wire.id);assert.equal(h.steps.at(-1).changes.removed[0].id,wire.id);
const file=m.panelExport(removed,h),loaded=m.readPanelFile(JSON.parse(JSON.stringify(file)));
assert.equal(loaded.history.steps.length,6);assert.ok(m.samePractice(loaded.practice,removed));
assert.equal(m.readPractice(file).wires.length,0);
checks.push('Panel JSON conserva circuito, seis pasos y operaciones Deshacer/Rehacer; el lector de práctica antiguo conserva compatibilidad.');
const corrupted=structuredClone(file);corrupted.panelHistory.steps[0].changes.added=[];
assert.throws(()=>m.readPanelFile(corrupted),/cambios del paso 1/);
const divergent=structuredClone(file);divergent.wires=[wire];
assert.throws(()=>m.readPanelFile(divergent),/circuito final no coincide/);
const unknown=structuredClone(file);unknown.panelHistory.steps[0].frame.practice.wires[0].to.terminalId='INVENTADO:1';
assert.throws(()=>m.readPanelFile(unknown),/cable no válido/);
checks.push('Metadatos de cambios alterados, estado final incompatible y bornes inventados rechazados antes de importar.');
const wrongLabel=structuredClone(file);wrongLabel.panelHistory.steps[3].label='Conectar cable';assert.match(m.readPanelFile(wrongLabel).history.steps[3].label,/Retirar/);
const legacy=structuredClone(h);legacy.steps.forEach(s=>{delete s.changes;delete s.operation;});
const recovered=m.readSession(legacy);assert.equal(recovered.steps[3].changes.removed.length,1);
assert.equal(m.readPanelFile(legacy).history.steps.length,6);
const snapshot=m.readPanelFile(add);assert.equal(snapshot.history.steps.length,0);assert.match(snapshot.message,/no se pueden reconstruir/);
checks.push('Grabaciones anteriores se migran comparando sus estados; JSON de montaje sin historial no inventa pasos.');
const reversed={...wire,from:wire.to,to:wire.from};
const diff=m.frameChanges(m.newFrame(add),m.newFrame({...add,wires:[reversed]}));
assert.deepEqual(diff.modified[0].fields,['from','to']);
let rolling=m.newPanelHistory(add);for(let i=0;i<205;i++)rolling=m.appendPanelHistory(rolling,{practice:{...add,wires:[{...wire,layer:i+1}]}},'Orden visual');
assert.equal(rolling.steps.length,200);assert.equal(rolling.truncated,true);assert.equal(rolling.initial.practice.wires[0].layer,5);assert.equal(m.readSession(rolling).steps.length,200);
checks.push('Cambios de extremos detectados; historial de 200 pasos acotado y tramo restante coherente.');
fs.writeFileSync(out+'/model-verification.json',JSON.stringify({result:'PASS',checks},null,2));
fs.writeFileSync(out+'/panel-fixture.json',JSON.stringify(file,null,2));
console.log(JSON.stringify({result:'PASS',checks},null,2));
