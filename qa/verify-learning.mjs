import assert from 'node:assert/strict';
import fs from 'node:fs';
import {build} from 'esbuild';
await build({entryPoints:['src/data/learning.ts','src/data/wiring.ts'],bundle:true,platform:'node',format:'esm',outdir:'qa/aprendizaje/model',logLevel:'silent'});
const {learningModel,netForLine,netComplete,assessCable,nextPair,newLearning,completedDiagramLines,canBind}=await import('./aprendizaje/model/learning.js?'+Date.now());
const {createCable,readPractice}=await import('./aprendizaje/model/wiring.js?'+Date.now());
const model=learningModel(),net=netForLine(77,model),[a,b,c]=net.terminals;
assert.ok(netForLine(23,model).terminals.includes('CONTACTOR_TERMICO:71'),'User confirmed KM1:11 is the thermal module 71');
assert.ok(netForLine(90,model).terminals.includes('CONTACTOR_TERMICO:72'),'User confirmed KM1:12 is the thermal module 72');
assert.ok(netForLine(83,model).terminals.includes('CONTACTOR_TERMICO:95'));
assert.ok(!netForLine(83,model).terminals.includes('CONTACTOR_TERMICO:96'),'Never join protection contact 95–96 internally');
assert.equal(model.flatMap(n=>n.lineIds).length,47);
assert.equal(new Set(model.flatMap(n=>n.lineIds)).size,47);
assert.equal(net.pairs.length,2);
assert.deepEqual(net.missing,[]);
let wires=[createCable(a,c,[])];
assert.equal(assessCable(wires[0],wires,model,{}),'correct');
assert.ok(completedDiagramLines(wires,model,{}).length>0,'Correct partial bridge colors a source path');
assert.ok(completedDiagramLines(wires,model,{}).length<net.lineIds.length,'One bridge must not mark the entire branched net complete');
assert.equal(netComplete(net,wires,model,{}),false);
wires.push(createCable(c,b,wires));
assert.equal(netComplete(net,wires,model,{}),true,'Alternative chain completes the same three-terminal net');
assert.equal(nextPair(net,wires),undefined);
assert.equal(netComplete(net,wires.slice(0,1),model,{}),false,'Removal invalidates completion');
const wrong=createCable(a,'BORNERA_MOTOR:U1',wires);
assert.equal(assessCable(wrong,[...wires,wrong],model,{}),'incorrect');
assert.equal(netComplete(net,[...wires,wrong],model,{}),false,'Contamination prevents false completed net');
const unknown=createCable(a,'TEMPORIZADOR_1:A1',wires);
assert.equal(assessCable(unknown,[...wires,unknown],model,{}),'unknown');
assert.equal(netComplete(net,[...wires,unknown],model,{}),false,'Unknown branch is not silently certified');
assert.equal(canBind('-KM1:A1',a,{}),false,'Cannot reuse a default physical terminal');
assert.equal(canBind('-invented:1','FUENTE:F',{}),false);
assert.ok(!netForLine(20,model).lineIds.includes(103),'Q of 24 V control is distinct from Q of three-phase power');
const bindings={'-X:L1':'FUENTE:R','-X:N':'FUENTE:N','-KM1:A2':'CONTACTOR_TRIFASICO:A2'};
const mapped=learningModel(bindings);
let supply=[createCable('FUENTE:R','CONTACTOR_TRIFASICO:A2',[])];
supply.push(createCable('CONTACTOR_TRIFASICO:A2','FUENTE:N',supply));
assert.equal(assessCable(supply[1],supply,mapped,bindings),'short','Transitive cables join explicitly mapped different potentials');
assert.equal(assessCable(createCable('FUENTE:F','FUENTE:TP',[]),[],model,{}),'incorrect','Explicit lesson mappings keep F separate from protection TP');
const doc={version:2,title:'QA',mode:'free',stepIndex:0,diagram:null,steps:[],wires,learning:{...newLearning(),bindings,index:30,assistance:3,answers:{0:'Explicación de prueba'}}};
assert.deepEqual(readPractice(JSON.parse(JSON.stringify(doc))),doc,'Learning progress portable');
assert.throws(()=>readPractice({...doc,learning:{...doc.learning,index:47}}));
assert.throws(()=>readPractice({...doc,learning:{...doc.learning,bindings:{'-fake:1':'FUENTE:R'}}}));
assert.throws(()=>readPractice({...doc,learning:{...doc.learning,bindings:{'-KM1:A1':a}}}));
const result={result:'PASS',checks:['47 original lines, source nodes with separate power and control breakers','Equivalent two-bridge chains accepted, removal invalidates progress','Partial correct connections color real diagram paths','Cross-net connections rejected; unknown endpoints and branches remain unevaluated','Source-only transitive short detection, no inferred F/TP behavior','Safe mappings and complete learning JSON round trip']};
fs.writeFileSync('qa/aprendizaje/model-verification.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
