import assert from 'node:assert/strict';
import fs from 'node:fs';
import {planArmMotion} from '../src/robotics/arm/motion.ts';
import {armCollision, gravityTorques, withAngles} from '../src/robotics/arm/kinematics.ts';
import {createDropWorld} from '../src/robotics/arm/drop.ts';
import {ARM_ID, ARM_TEMPLATE, BLOCK_ID, ZONE_ID, JOINTS, HOME, approachArm, armFrames, armAngles, buildArmPractice, delivered, gripArm, heldId, moveArm, resetArmPractice} from '../src/robotics/arm/model.ts';
import {buildTemplate, buildReadyRobot} from '../src/robotics/project/templates.ts';
import {catalogShape, definitionIds} from '../src/robotics/catalog/index.ts';
import {parseRobotProject} from '../src/robotics/project/validate.ts';
import {readLibrary} from '../src/robotics/project/library.ts';
import {qRotate} from '../src/robotics/project/math.ts';
const checks = [], pass = s => {checks.push(s); console.log('PASS', s);};
let p = buildTemplate(ARM_TEMPLATE), arm = p.parts.find(x => x.definitionId === ARM_ID), id = arm.instanceId;
for(const reference of JSON.parse(fs.readFileSync('qa/robotics-arm/urdf-fixtures.json','utf8'))){
 const frame=armFrames(withAngles(arm,reference.angles)).tcp;
 assert.ok(frame.position.every((v,i)=>Math.abs(v-reference.tcp[i])<1e-10));
 for(const [i,axis] of [[1,0,0],[0,1,0],[0,0,1]].entries())assert.ok(qRotate(frame.rotation,axis).every((v,j)=>Math.abs(v-reference.axes[i][j])<1e-10));
}
pass('Cinemática de posición y orientación coincide con tres referencias independientes calculadas desde el URDF oficial.');
const block = p.parts.find(x => x.definitionId === BLOCK_ID), zone = p.parts.find(x => x.definitionId === ZONE_ID);
assert.equal(p.firmware.length, 0); assert.ok(parseRobotProject(p, {catalog: catalogShape, knownDefinitions: definitionIds}).ok);
const original = JSON.stringify(p);
assert.equal(moveArm(p, id, [NaN, 0, 0, 0, 0, 0]).ok, false);
assert.equal(approachArm(p, id, [2, .1, 0]).ok, false);
assert.equal(JSON.stringify(p), original);
assert.equal(heldId(gripArm(p, id, false).project.parts[0]), '');
assert.equal(delivered(p), false);
assert.equal(delivered({...p, parts: p.parts.map(x => x.definitionId === BLOCK_ID ? {...x, transform: {...x.transform, position: [zone.transform.position[0], .0175, zone.transform.position[2]]}} : x)}), false, 'mover el cubo a mano no sustituye el depósito con pinza');
pass('Plantilla y catálogo válidos; no inventa firmware; comandos inválidos y agarre lejano no alteran la práctica.');
const target = [block.transform.position[0], .025, block.transform.position[2]];
let r = approachArm(p, id, target); assert.ok(r.ok, r.message); p = r.project;
let tcp = armFrames(p.parts[0]).tcp.position;
assert.ok(Math.hypot(...tcp.map((v, i) => v - target[i])) < .0005, 'cinemática inversa llega al objetivo');
p = gripArm(p, id, false).project; assert.equal(heldId(p.parts[0]), block.instanceId);
assert.ok(p.parts.find(x => x.instanceId === block.instanceId).locked);
p = moveArm(p, id, HOME).project;
assert.deepEqual(p.parts.find(x => x.instanceId === block.instanceId).transform, armFrames(p.parts[0]).tcp);
const highRelease=gripArm(p,id,true);assert.ok(highRelease.ok);assert.ok(highRelease.project.parts.find(x=>x.instanceId===block.instanceId).transform.position[1]>.08,'soltar no teletransporta la pieza al suelo');
assert.equal(delivered(p), false, 'levantar no completa el objetivo');
pass('Acercamiento, agarre por proximidad y seguimiento de la herramienta; liberación en altura conserva la posición antes de caer.');
r = approachArm(p, id, [zone.transform.position[0], .025, zone.transform.position[2]]); assert.ok(r.ok, r.message); p = r.project;
assert.equal(delivered(p), false, 'estar sobre la zona con pieza sujeta no completa');
p = gripArm(p, id, true).project;
const world=await createDropWorld(p,p.parts.find(x=>x.instanceId===block.instanceId),p.parts[0]);
let fall;for(let i=0;i<600;i++){fall=world.step();if(fall.done)break;}world.free();
p={...p,parts:p.parts.map(x=>x.instanceId===block.instanceId?{...x,transform:fall.transform}:x)};
assert.equal(heldId(p.parts[0]), ''); assert.ok(delivered(p));
assert.equal(p.parts.find(x => x.instanceId === block.instanceId).locked, false);
const reload = readLibrary(JSON.stringify({projects: [p, buildReadyRobot()], active: p.id}));
assert.equal(reload.status, 'ok'); assert.ok(delivered(reload.library.projects[0]));
assert.deepEqual(armAngles(reload.library.projects[0].parts[0]), armAngles(p.parts[0]));
const reset = resetArmPractice(p, id); assert.ok(reset.ok); assert.equal(delivered(reset.project), false);
assert.deepEqual(armAngles(reset.project.parts[0]), HOME);
assert.ok(reset.project.parts[1].transform.position.every((v, i) => Math.abs(v - [.28, .0175, .10][i]) < 1e-10));
pass('Práctica completa solo al soltar dentro de zona; estado y articulaciones sobreviven al guardado junto a un robot anterior.');
let heavy = buildArmPractice(); const hId = heavy.parts[0].instanceId;
heavy = {...heavy, parts: heavy.parts.map(x => x.definitionId === BLOCK_ID ? {...x, props: {massKg: 1}} : x)};
heavy = approachArm(heavy, hId, target).project;
assert.equal(gripArm(heavy, hId, false).ok, false);
assert.equal(moveArm(buildArmPractice(), 'brazo-inexistente', HOME).ok, false);
const bench = buildArmPractice();
assert.equal(moveArm(bench, bench.parts[0].instanceId, [0, -130, -150, 0, 0, 0]).ok, false);
const clamped = moveArm(bench, bench.parts[0].instanceId, [9999, ...HOME.slice(1)]);
assert.equal(armAngles(clamped.project.parts[0])[0], JOINTS[0].max);
assert.equal(armCollision(bench,bench.parts[0]),null);
const destination=approachArm(bench,bench.parts[0].instanceId,[.28,.20,.1]);assert.ok(destination.ok);
const plan=planArmMotion(bench,bench.parts[0].instanceId,armAngles(destination.project.parts[0]),'MovJ',50);assert.ok(plan.ok);
let last=HOME;const dt=plan.duration/plan.frames.length;
for(const frame of plan.frames){assert.ok(frame.every((v,i)=>Math.abs(v-last[i])/dt<=JOINTS[i].velocity*.5+.1));last=frame;}
const lower=approachArm(destination.project,bench.parts[0].instanceId,[.28,.025,.1]);assert.ok(lower.ok);
const linear=planArmMotion(destination.project,bench.parts[0].instanceId,armAngles(lower.project.parts[0]),'MovL',50);assert.ok(linear.ok,linear.message);
for(const frame of linear.frames){const v=armFrames(withAngles(bench.parts[0],frame)).tcp.position;assert.ok(Math.abs(v[0]-.28)<.001&&Math.abs(v[2]-.1)<.001,'MovL conserva la recta del TCP');}
const blocked={...bench,scene:{...bench.scene,obstacles:[{id:'bloqueo',shape:'box',transform:{position:[0,.25,-.2],rotation:[0,0,0,1]},size:[.5,.4,.5]}]}};
assert.equal(planArmMotion(blocked,bench.parts[0].instanceId,armAngles(destination.project.parts[0])).ok,false);
assert.ok(gravityTorques(bench.parts[0],.5).every(Number.isFinite));
assert.ok(gravityTorques(bench.parts[0],.5).some((v,i)=>Math.abs(v-gravityTorques(bench.parts[0])[i])>.1));
const programmed={...bench,armProgram:{armId:bench.parts[0].instanceId,points:[{name:'P1',angles:HOME,gripperOpen:true,kind:'MovJ'}]}};
assert.deepEqual(parseRobotProject(programmed,{catalog:catalogShape}).project.armProgram,programmed.armProgram);
assert.equal(parseRobotProject({...programmed,armProgram:{...programmed.armProgram,points:[{...programmed.armProgram.points[0],angles:[NaN]}]}}).ok,false);
pass('MovJ respeta velocidad; MovL sigue una recta; colisión rechaza trayectoria; carga cambia el par; programa serializa y valida.');
pass('Carga excesiva, límite articular, brazo inexistente y penetración del suelo comprobados.');
fs.mkdirSync('qa/robotics-arm', {recursive: true});
fs.writeFileSync('qa/robotics-arm/model-results.json', JSON.stringify({checks}, null, 2));
