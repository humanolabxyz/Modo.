import assert from 'node:assert/strict';
import fs from 'node:fs';
import R from '@dimforge/rapier3d-compat';
import {buildReadyRobot, buildRover4wd, buildSumoRobot} from '../src/robotics/project/templates.ts';
import {newRobotProject} from '../src/robotics/project/defaults.ts';
import {setPartProp} from '../src/robotics/project/commands.ts';
import {arenaEligibility, prepareArena, ArenaMatch, judgeArena} from '../src/robotics/arena/model.ts';
import {RobotPhysics} from '../src/robotics/sim/physics.ts';
const out='qa/robotics-arena';fs.mkdirSync(out,{recursive:true});const checks=[];
const pass=s=>{checks.push(s);console.log('PASS',s);};
await R.init();
const a=buildSumoRobot(),b=buildRover4wd(),before=JSON.stringify([a,b]);
assert.equal(arenaEligibility(a).error,undefined);assert.equal(arenaEligibility(b).error,undefined);
assert.ok(arenaEligibility(newRobotProject()).error);
assert.ok(arenaEligibility({...a,attachments:a.attachments.slice(1)}).error);
assert.ok(arenaEligibility({...a,firmware:a.firmware.map(f=>({...f,source:f.source+'\n// edit'}))}).error);
pass('Entrada: exige robot unido, ruedas, una placa y programa vigente; rechaza vacío, piezas sueltas y HEX desactualizado.');
const p=prepareArena(a,a);assert.equal(new Set(p.project.parts.map(x=>x.instanceId)).size,a.parts.length*2);
for(const connection of p.project.connections) for(const ref of [connection.a,connection.b]) assert.ok(p.project.parts.some(x=>x.instanceId===ref.instanceId));
assert.equal(p.project.scene.obstacles.length,0);assert.equal(p.project.scene.lineTrack.points.length,128);
pass('Dos copias del mismo robot tienen IDs separados y cableados aislados, sin modificar los originales.');
assert.deepEqual(judgeArena([[.76,.04,0],[0,.04,0]],[0,0],.149,1,30).result,null);
assert.equal(judgeArena([[.76,.04,0],[0,.04,0]],[.149,0],.002,1,30).result.winner,1);
assert.equal(judgeArena([[.76,.04,0],[-.76,.04,0]],[.149,.149],.002,1,30).result.winner,null);
assert.equal(judgeArena([[0,.04,0],[0,.04,0]],[.1,0],.002,30,30).result.reason,'tiempo agotado');
assert.deepEqual(judgeArena([[0,.04,0],[0,.04,0]],[.1,0],.002,1,30).outside,[0,0]);
assert.equal(judgeArena([[0,-.07,0],[0,.04,0]],[.149,0],.002,1,30).result.winner,1);
pass('Árbitro: salida sostenida, caída, reentrada, salida simultánea y límite de tiempo.');
const off=setPartProp(a,a.parts.find(x=>x.definitionId==='power-switch').instanceId,'closed',false);
assert.throws(()=>new ArenaMatch(R,off,b),/alimentación/);
pass('Un interruptor abierto impide el combate; no se inventa potencia para mover el robot.');
// Straight drive makes an exact repeatable head-on contact test, independent of avoidance strategies.
const drive=project=>({...project,firmware:project.firmware.map(f=>({...f,artifact:{...f.artifact,origin:'hex-import',hex:fs.readFileSync('qa/fixtures/robotica/motors_fwd.hex','utf8')}}))});
const straight=drive(buildReadyRobot()),prepared=prepareArena(straight,straight);
const phys=RobotPhysics.create(R,prepared.project,{arenaRadius:.75,teams:prepared.teams});
for(let i=0;i<200;i++)phys.step(new Map());
const sensor=prepared.robots[0].parts.find(x=>x.definitionId==='hc-sr04').instanceId;
const measured=phys.distance(sensor);assert.ok(measured>.2&&measured<.7,`ultrasonido ve al rival: ${measured}`);phys.dispose();
pass('El HC-SR04 mide al rival en el mundo compartido y excluye su propio robot.');
const match=new ArenaMatch(R,straight,straight,4);
for(let i=0;i<1490;i++)match.step();
assert.equal(match.frame().countdown,1);assert.equal(match.frame().elapsed,0);
assert.equal(match.frame().physics.impacts.length,0,'no hay efectos de choque por tocar el suelo ni antes de competir');
const start=match.frame().roots.map(id=>match.frame().physics.poses[id].p);
assert.ok(start[0][2]<-.34&&start[1][2]>.34,'no arranca antes de la cuenta regresiva');
let gap=Infinity;
while(!match.frame().result){match.step();const f=match.frame(),pos=f.roots.map(id=>f.physics.poses[id].p);gap=Math.min(gap,Math.hypot(pos[0][0]-pos[1][0],pos[0][2]-pos[1][2]));}
const end=match.frame();assert.ok(gap>.18&&gap<.5,`contacto físico sin atravesarse; mínima separación ${gap}`);
assert.ok(end.physics.impacts.length>0,'el contacto entre rivales genera eventos reales para los efectos');
assert.ok(end.physics.impacts.every(x=>x.at>=3&&x.position.every(Number.isFinite)));
assert.ok(Math.abs(end.elapsed-4)<.003,'un solo paso del mundo por cada pareja de pasos Arduino');
const frozen=JSON.stringify(end);match.step();assert.equal(JSON.stringify(match.frame()),frozen);match.dispose();
pass('Dos programas independientes: cuenta regresiva inmóvil, choque sin atravesarse, reloj compartido y detención al terminar.');
// Forward-only robot versus an unpowered driver but powered MCU: a real push and ring-out.
const defender=drive(buildReadyRobot());const motorIds=defender.parts.filter(x=>x.definitionId==='dc-motor-tt').map(x=>x.instanceId);
const passive={...defender,connections:defender.connections.filter(c=>!motorIds.includes(c.a.instanceId)&&!motorIds.includes(c.b.instanceId))};
const push=new ArenaMatch(R,straight,passive,20);while(!push.frame().result)push.step();
assert.equal(push.frame().result.reason,'salida');assert.equal(push.frame().result.winner,0);
const pushResult=push.frame().result;push.dispose();
assert.equal(JSON.stringify([a,b]),before);
pass('Empuje real saca al rival sin motores del círculo y otorga victoria; proyectos fuente intactos.');
fs.writeFileSync(out+'/model-results.json',JSON.stringify({checks,gap,pushResult},null,2));
