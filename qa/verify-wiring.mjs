import assert from 'node:assert/strict';
import fs from 'node:fs';
import {build} from 'esbuild';
await build({entryPoints:['src/data/wiring.ts'],bundle:true,platform:'node',format:'esm',outfile:'qa/fase2/wiring-test.mjs',logLevel:'silent'});
const {createCable,cableNodes,connectedByCables,readPractice,cableGeometry,TERMINAL_BY_ID}=await import('./fase2/wiring-test.mjs?'+Date.now());
const a='FUENTE:F',b='BOTONERAS:S1:3',c='CONTACTOR_TERMICO:A1',d='CONTACTOR_TERMICO:A2';
let wires=[createCable(a,b,[])];
assert.equal(connectedByCables(a,b,wires),true);
assert.equal(connectedByCables(c,d,wires),false,'No implicit coil edge');
wires.push(createCable(b,c,wires));
assert.equal(connectedByCables(a,c,wires),true,'Transitive cable-only node');
assert.equal(connectedByCables(c,d,wires),false,'Components never union internally');
assert.equal([...cableNodes(wires).values()][0].length,3);
assert.equal(connectedByCables(a,c,wires.slice(1)),false,'Removing a cable splits topology');
for(const id of [...TERMINAL_BY_ID.keys()].slice(0,20)){if(id!==a)wires.push(createCable(a,id,wires))}
assert.ok(wires.filter(w=>w.from.terminalId===a).length>3);
assert.equal(new Set(wires.map(w=>w.id)).size,wires.length);
assert.throws(()=>createCable(a,a,wires));assert.throws(()=>createCable('UNKNOWN',a,wires));
const doc={version:2,title:'QA',mode:'free',stepIndex:0,diagram:null,steps:[],wires};
assert.deepEqual(readPractice(JSON.parse(JSON.stringify(doc))),doc);
assert.throws(()=>readPractice({...doc,wires:[...wires,wires[0]]}));
assert.throws(()=>readPractice({...doc,diagram:{id:'x',name:'x',src:'https://unreviewed.example/test.svg',origin:'user_image'}}));
const g=cableGeometry(wires.at(-1),wires);assert.ok(g.from.head.x>g.from.point.x,'Shared endpoint heads fan out');
const reviewed={id:'manual',title:'Par revisado',from:a,to:b,region:{x:100,y:100,w:80,h:100},explanation:'Dato revisado por quien estudia.',review:'user_reviewed'};
assert.equal(readPractice({...doc,diagram:{id:'clase-1',name:'Clase 1',src:'/diagrams/clase-1.jpg',origin:'class_photo'},steps:[reviewed]}).steps.length,1);
assert.throws(()=>readPractice({...doc,diagram:{id:'clase-1',name:'Clase 1',src:'/diagrams/clase-1.jpg',origin:'class_photo'},steps:[{...reviewed,review:'unreviewed'}]}));
assert.throws(()=>readPractice({...doc,steps:[reviewed]}));
const evidence={result:'PASS',checks:['Explicit endpoints, unique cable IDs','Cable-only union nodes; no internal component or N/TP assumptions','Transitive connections and split after removal','More than three cables on a terminal with independent heads','JSON round trip and invalid import rejection','Manual region/endpoint review required'],wireCount:wires.length};
fs.writeFileSync('qa/fase2/wiring-verification.json',JSON.stringify(evidence,null,2));
console.log(JSON.stringify(evidence,null,2));
