/* Sonidos de los elementos: al accionar el banco se pide el sonido de cada elemento, en el orden en que ocurre en el equipo real.
 * Se comprueba el registro interno (window.__panelSounds); la salida de audio real no se puede oír en una prueba automática. */
const assert=require('node:assert/strict'),fs=require('node:fs');
const {chromium}=require('C:/Users/HUMANO LAB/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base=(process.env.PANELLAB_URL||'http://127.0.0.1:4410').replace(/\/$/,''),out=process.env.PANELLAB_QA_OUTPUT||'qa/element-sounds',report={base,checks:[],errors:[]};
fs.mkdirSync(out,{recursive:true});
const lessonModel=process.env.LESSON_MODEL||'qa/two-contactor-lesson/model.cjs';
(async()=>{
 const m=require('./'+lessonModel.replace(/^qa\//,''));
 const browser=await chromium.launch();
 const c=await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block',reducedMotion:'reduce'});
 await c.addInitScript(()=>{localStorage.setItem('modo-tutoriales-bienvenida-v1','seen');localStorage.removeItem('panellab.sonidos.v1');});
 const p=await c.newPage();p.setDefaultTimeout(20000);p.on('pageerror',e=>{report.errors.push(e.message);console.log('PAGEERROR',e.message);});
 const sounds=()=>p.evaluate(()=>[...(window.__panelSounds||[])]);
 const clear=()=>p.evaluate(()=>{if(window.__panelSounds)window.__panelSounds.length=0;});
 await p.goto(base+'/?view=simulator');await p.locator('.board-svg').waitFor();await p.waitForFunction(()=>!document.getElementById('modo-splash'));
 await p.getByRole('button',{name:'Guía paso a paso',exact:true}).click();
 await p.getByRole('button',{name:'Aprender: Estrella-triángulo · 2 contactores',exact:true}).click();await p.locator('.guide-window').waitFor();
 const wires=m.TWO_CONTACTOR_LESSON.pairs.map(([a,b],i)=>({id:'lw'+i,from:{terminalId:a},to:{terminalId:b},color:'#145650',route:{sag:130},layer:i+1}));
 await p.evaluate(([w,n])=>{const k='panellab-practice-v2',d=JSON.parse(localStorage.getItem(k));d.wires=w;d.stepIndex=n;localStorage.setItem(k,JSON.stringify(d));},[wires,wires.length]);
 await p.reload();await p.locator('.board-svg').waitFor();await p.waitForFunction(()=>!document.getElementById('modo-splash'));
 await p.getByRole('button',{name:/Ocultar la guía/}).click().catch(()=>{});
 await p.getByLabel('Simular mando de 24 V',{exact:true}).click();await p.getByLabel('Opciones de simulación',{exact:true}).click();
 const d=p.getByRole('dialog',{name:'Simulación · 24 V',exact:true});
 await p.getByLabel('Retardo del temporizador',{exact:true}).selectOption('2');
 await clear();
 await d.getByRole('button',{name:'Enchufar corriente virtual',exact:true}).click();
 for(const name of ['FUERZA · OFF','CONTROL 1 · OFF','CONTROL 2 · OFF'])await d.getByRole('button',{name,exact:true}).click();
 let log=await sounds();
 assert.ok(log.includes('enchufe'),'enchufe: '+log);assert.ok(log.includes('interruptor:FUERZA'),'FUERZA');assert.ok(log.includes('interruptor:CONTROL1')&&log.includes('interruptor:CONTROL2'),'CONTROL');
 report.checks.push('Enchufe e interruptores FUERZA/CONTROL suenan: '+log.join(' · '));
 await p.getByRole('button',{name:'Cerrar simulación · 24 v',exact:true}).click();
 await clear();
 const start=p.getByRole('button',{name:'Pulsador verde izquierdo',exact:true});
 await start.focus();await p.keyboard.down('Space');await p.waitForTimeout(400);
 log=await sounds();
 assert.ok(log.includes('pulsador-abajo:S1'),'pulsador abajo: '+log);
 assert.ok(log.includes('contactor-cierra:TEMPORIZADOR_1')&&log.includes('contactor-cierra:CONTACTOR_TRIFASICO'),'KT1 y KM2 cierran: '+log);
 assert.ok(log.indexOf('pulsador-abajo:S1')<log.indexOf('contactor-cierra:TEMPORIZADOR_1'),'primero el pulsador y después el contactor');
 await p.keyboard.up('Space');await p.waitForTimeout(150);
 log=await sounds();assert.ok(log.includes('pulsador-arriba:S1'),'pulsador arriba');
 report.checks.push('S1: pulsador, cierre de KT1 y KM2 y pulsador al soltar: '+log.join(' · '));
 await clear();
 await p.locator('[data-motor-connection=delta]').waitFor({timeout:8000});await p.waitForTimeout(300);
 log=await sounds();
 assert.ok(log.includes('temporizado:TEMPORIZADOR_1'),'fin del retardo: '+log);
 assert.ok(log.includes('contactor-abre:CONTACTOR_TRIFASICO'),'KM2 abre: '+log);
 assert.ok(log.includes('contactor-cierra:CONTACTOR_TERMICO'),'KM1 cierra: '+log);
 report.checks.push('Cambio a triángulo: temporizador, KM2 abre y KM1 cierra: '+log.join(' · '));
 await clear();
 await p.getByLabel('Opciones de simulación',{exact:true}).click();
 await p.getByRole('button',{name:'Disparar térmico',exact:true}).click();await p.waitForTimeout(300);
 log=await sounds();
 assert.ok(log.includes('termico-dispara'),'térmico dispara: '+log);assert.ok(log.some(s=>s.startsWith('contactor-abre')),'los contactores caen: '+log);
 report.checks.push('TEST: chasquido del térmico y caída de los contactores: '+log.join(' · '));
 await clear();
 const mute=p.getByRole('button',{name:'Silenciar los sonidos de los elementos'}).first();
 await mute.click();
 await p.getByRole('button',{name:'Rearmar térmico',exact:true}).click();await p.waitForTimeout(300);
 assert.deepEqual(await sounds(),[],'con los sonidos silenciados no se pide ninguno');
 assert.equal(await p.evaluate(()=>localStorage.getItem('panellab.sonidos.v1')),'0','el silencio se recuerda');
 report.checks.push('El botón de sonido silencia todo y se recuerda');
 assert.deepEqual(report.errors,[]);
 fs.writeFileSync(out+'/results.json',JSON.stringify(report,null,2));console.log(report.checks.map(s=>'PASS '+s).join('\n'));
 await browser.close();
})().catch(e=>{console.log('FAIL',e.stack||e.message);process.exit(1);});
